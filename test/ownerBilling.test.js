test('historical paid invoices appear as income without duplicating new completed invoices', async () => {
  const legacy = await platform.get().Invoice.create({ schoolId: school._id, number: 'INV-HISTORICAL', description: 'Historical invoice', amountMinor: 12300, status: 'paid', paidAt: new Date(), dueDate: today, dueAt: billing.dueAt(today), createdBy: owner._id, updatedBy: owner._id });
  let report = (await call('get', `/api/owner/finance-report?type=invoice&startDate=${today}&endDate=${today}`).expect(200)).body;
  assert.equal(report.summary.incomeMinor, 1074300);
  assert.equal(report.items.filter(i => i.number === legacy.number).length, 1);
  await platform.connection().transaction(async session => {
    await require('../src/services/ownerFinance').complete(legacy, school, owner._id, session);
  });
  report = (await call('get', `/api/owner/finance-report?type=invoice&startDate=${today}&endDate=${today}`).expect(200)).body;
  assert.equal(report.summary.incomeMinor, 1074300);
  assert.equal(report.items.filter(i => i.number === legacy.number).length, 0);
});
