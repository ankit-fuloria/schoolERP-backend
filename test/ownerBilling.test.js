  await call('post', '/api/owner/expenses', { ...body, transactionDate: '2026-02-30' }).expect(400);
  await call('post', '/api/owner/expenses', { ...body, transactionDate: '2099-01-01' }).expect(400);
  await call('post', '/api/owner/expenses', { ...body, method: 'invalid' }).expect(400);
  await call('post', '/api/owner/expenses', body, teacherToken).expect(403);
  await call('get', '/api/owner/expenses', undefined, principalToken).expect(403);
  await call('get', '/api/owner/finance-report', undefined, principalToken).expect(403);
  await call('get', '/api/owner/completed-invoices', undefined, teacherToken).expect(403);
  const expense = (await call('post', '/api/owner/expenses', body).expect(201)).body;
  assert.equal((await call('post', '/api/owner/expenses', body).expect(201)).body._id, expense._id);
  await call('post', '/api/owner/expenses', { ...body, amountMinor: 20000 }).expect(409);
  await call('post', '/api/owner/expenses', { ...body, requestId: 'expense-salary', category: 'Development', amountMinor: 5000 }).expect(201);
