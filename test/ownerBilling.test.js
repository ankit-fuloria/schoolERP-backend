  assert.ok(completed); assert.equal(completed.amountMinor, 1062000); assert.equal(completed.taxMinor, 162000);
  assert.equal(completed.billNumber, invoice.number);
  assert.equal(await platform.get().CompletedInvoice.countDocuments({ billId: invoice._id }), 1);
  const mails = await platform.get().Mail.find({ key: new RegExp(`^completed-invoice:${completed._id}`) });
