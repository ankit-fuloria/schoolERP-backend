  assert.equal(adjusted.summary.expenseMinor, 5000); assert.equal(adjusted.summary.netMinor, -5000);
  assert.equal(adjusted.items.find(i => i._id === expense._id).signedMinor, 0);
  assert.equal(await platform.get().Expense.countDocuments(), 2);
  await call('get', `/api/owner/finance-report?startDate=${today}&endDate=2000-01-01`).expect(400);
  await call('get', '/api/owner/expenses?limit=5000').expect(400);
